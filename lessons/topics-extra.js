詞牌與題目
詞牌規定曲調所對應的句式、字數、用韻等格式；同一詞牌可以填寫不同主題。另附的詞題、詞序或正文才有助判斷內容。有些作品沒有另立題目。
若兩張作品卡都題「如夢令」，一張寫郊遊，一張寫惜別，仍可採同一調式。編目的「詞牌」欄相同，「題材」欄應依各篇文字分開填。
詞牌名稱的字面容易引人聯想，例如看到「漁」就想著捕魚。只有正文真的出現相關情節，才能把釣魚填進主題摘要。

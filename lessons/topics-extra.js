轉化
把動作的主詞和受詞找出來，再想這種動作或性情通常屬於誰。物有人的言行是擬人，人被寫成物也屬轉化，可以藉此讀出敘述者對場景的感受。
「公車在山腳打了個哈欠」把哈欠交給車子。若下一句是「車門慢慢張開」，兩個動作連起來，就讀得出早晨懶洋洋的氣氛。
不能只看句中出現動詞。「雨滴落下」是自然現象；若寫成「雨滴敲門討杯茶」，才賦予雨滴人的意圖。

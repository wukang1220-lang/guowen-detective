誇飾
先找被拉大或縮小的尺度，可能是長短、音量、程度或時間。把原句改寫成平實的描述，再比較情緒少了多少，就能說明誇飾的作用。
「等公布名單的這一分鐘長過一學期」仍是等了一分鐘。拿它和一學期比較，把等待時的焦急寫出來；排活動流程時要採用鐘錶時間。
醒目的數字也可能是實測值。讀到「一百次」要先辨認這是抱怨、口號，還是有逐次紀錄可查。

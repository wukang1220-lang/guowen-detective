映襯
把同段中形成對照的兩個畫面並排，再找它們共有的比較項目，例如聲響、明暗或動靜。最後看敘事把視線留給哪一方，才能讀出作者想突出的意義。
「操場的歡呼像浪，保健室裡卻只聽得見時鐘」同寫校園的聲音。把喧鬧擺在前面，後面的滴答聲便特別清楚，也讓等待顯得更孤單。
僅把兩件事情寫在一起，還不足以判成映襯。要找得到彼此牽動的特徵，也要說得出比較後什麼變得更鮮明。
展覽入口燈火通明，修復室卻只亮著一盞桌燈。記者從入口掠過，把鏡頭停在燈下補紙的雙手。
兩種光線放在一起，主要凸顯什麼？|幕後工作者安靜專注的身影|展場的用電支出|記者偏好暗色衣服|鏡頭最後停在修復者手上，明暗對照把注意力引向幕後。
刪去入口的描述，讀者會少感受到哪一層？|熱鬧展場與安靜後場的差異|修復室裡有人補紙|桌燈提供光線|單留修復室仍可讀到補紙動作，但少了明暗對照。
哪對詞最適合並排標記？|「燈火通明」與「只亮著一盞」|「入口」與「記者」|「桌燈」與「雙手」|兩詞沿著同一項目比較亮度，直接形成映襯。

倒反
遇見字面上的稱讚或責備，先核對事情的結果，再檢查語調、表情和上下文。若字面評價與真實態度方向相反，讀者就能從落差讀出諷刺或親暱。
「你可真準時，蛋糕都吃完了！」前半像稱讚，後半交代對方遲到。平實改寫成「你來得太晚了」，便能檢驗反話真正的意思。
事情令人意外不等於用了反話。要先找一句帶評價的原話，再找足以推翻字面評價的事實。
社長望著被雨淋濕的海報，指著忘了蓋箱子的幹部說：「這防水措施可真周到。」
社長的真正評價最接近哪一句？|防護做得不夠周全|箱蓋密合得很好|海報可以直接張貼|海報濕透且箱子沒蓋，使「周到」具有反諷意思。
若要把這句改成出於真心的稱讚，應改哪項事實？|大雨過後，密封箱裡的海報全是乾的|社長改在走廊裡說話|幹部多搬一把椅子|防護有效時，「周到」才和結果一致。
誰提出了可以查核的語氣依據？|阿澄說箱子沒蓋，海報已經淋濕|小禾說社長講話只有一句|墨點看見海報上有藍色的字|疏失和結果都與字面稱讚相反。

設問
先搜尋問句後有沒有回答。自問自答可引出作者的觀點；反問則常把肯定或否定的答案藏進語氣裡。讀完可試著改成直述句，確認真正要傳遞的意思。
「誰在天亮以前送來早餐？是街角那盞最早亮起的燈下的阿姨。」問句先引起好奇，後句揭曉答案，焦點才落到常被忽略的人。
不能看見問號就判斷作者不知道答案。若讀者和作者已能從上下文得出答案，問句可能在加強主張。
社論開頭寫：「一張廢紙還能去哪裡？走進工藝教室，你會看到它成了新生的紙漿。」結尾說：「我們怎能只把它當垃圾？」
開頭先問再答有什麼作用？|引出廢紙再利用的實例|要求讀者提供地址|否定工藝教室的存在|下一句已回答去向，問題用來吸引讀者看實例。
結尾若改成直述句，哪句最接近？|我們應該看見廢紙的其他用途|我們不知道廢紙在哪裡|我們只能把廢紙丟掉|「怎能只」含有否定「只能丟棄」的意思。
哪個依據最能區分兩個問句的功能？|第一問接實例作答，第二問用「怎能只」表態|兩句都有問號|兩句都談紙張|後續有無解答和問句語氣，比共同標點更能說明功能。

類疊
圈出重複出現的字或詞句，讀出節拍，再問每一次重複有沒有增添時間、情緒或動作。連在一起的疊字和隔句反覆，都可能把感受寫得更鮮明。
「等啊，等啊，車燈終於越過坡頂」若改成「等車到了」，事情相同，讀者卻少感受了人物在原地等待的那段時間。
辨認時先說清楚重複的單位。「越走越急」和「走，走，走」的結構不同，要依實際用字說明效果。
尋人廣播響起前，弟弟扶著欄杆念：「再看一眼，再看一眼。」直到站臺清空，他還望著那道門。
反覆念同一句，透露哪種心情？|捨不得放棄尋找|急著欣賞車站建築|對下一班車漠不關心|動作持續到人潮散去，重複的話把盼望拖長。
改成「弟弟看了一眼」會損失什麼？|一次又一次期待的節奏|事情發生在車站|站臺曾經有人|單次動作無法表現反覆等候。
哪一處聲音最直接造成這個節奏？|兩次完全相同的「再看一眼」|「欄杆」有兩個字|「弟弟」是人物稱呼|整個短句重現，正好模擬反覆眺望的動作。

排比
將相鄰分句逐一斷開，找三個或更多結構相近的單位。它們可以從不同角度鋪陳同一件事。讀時把共有的骨架留下，換入的詞最能指出內容如何擴大。
「有人收傘，有人擦桌，有人替客人引路」用三個「有人＋動作」呈現分工。若改成「現場很忙」，就少了三群人同時行動的畫面。
只列三個名詞未必形成清楚的分句排比。說明效果時要指出相似結構，也要交代各句合起來表現了什麼。
布展記錄寫：「有人量牆面的寬，有人試燈光的角，有人調展架的高。」老師把三行原封不動貼出來。
這種寫法最能呈現什麼？|多組人馬各司其職|三件工作由同一人先後完成|燈光比展架更重要|三個並列的「有人」讓同時分工的景象清楚可見。
哪一句最適合依原有結構續寫？|有人核標籤的字|展覽很好看|牆面是灰色的|「有人＋動作＋對象的細節」接得上前三項。
指出排比時，應保留哪組文字？|「有人量⋯⋯有人試⋯⋯有人調⋯⋯」|「布展」和「老師」|「寬」與「高」兩個字|三個相似分句連在一起，才看得出形式和節奏。

對偶
把上下兩句對齊，依序檢查字數、句法和意義是否呼應。例如上句的地點可對下句的地點，動作可對動作。接著看兩句是相輔還是相反。
「晨鐘催客起，暮鼓送舟還」中，晨對暮、鐘對鼓、催對送。兩行一早一晚，都能獨立讀通，放在一起又勾勒完整的一天。
對偶可以寫相近的意思，也可以寫對比。只因語義相反或兩行一樣長，都不足以判定結構工整。
展板上只剩上句「春風開畫卷」，三張下句草稿正等編輯審定。要求兩句以「景物＋動作＋事物」相對。

感嘆
先讀引發反應的事件，再觀察人物的動作和語氣。感嘆詞可以表露驚喜、失望、同情或讚美；讀者需要用前後文說明，為什麼此處是這一種情緒。
同樣是「啊！」，後面若接「票根找回來了」，配上舒展的眉頭，是鬆口氣；若接「車門關上了」，配上垂下雙肩，則可能是遺憾。
驚嘆號只提示語氣強烈，不能單獨確定是快樂、生氣或害怕。人物接下來做了什麼，往往比標點更有辨識力。
廣播劇裡，女孩聽見院門的鈴聲，先追出去，回來時握著遺失多日的貓牌笑道：「啊，總算找到了！」

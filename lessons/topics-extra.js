轉品
同一個詞在不同句子裡可能換了工作。拿熟悉的本義當起點，再看它前後接什麼、能否換成動詞。讀出這個變化，往往就能解釋一句短詩如何表現過程。
「晚霞紅了半面牆」中的「紅」後面接著牆。換成「使半面牆變紅」句意仍通；若寫「那是一面紅牆」，紅便回到描述顏色的位置。
字典裡常見的詞性只是起點。先把詞放回整句，留意它是在描述性質，還是正在表示動作或造成的變化。
音樂社的散文稿寫「晨霧白了整排屋頂」。照片裡，原本深灰的瓦片漸漸罩上白霧。

摹寫
把感官想成五欄。聲音、氣味、觸感、味道和可見的形色，各能補出場景的一部分。若題目要推斷地點或物件，優先選能區分候選答案的細節。
「麻繩在掌心磨出一圈粗痕」寫出觸覺；「繩尾啪地甩上木板」才提供可聽的撞擊聲。閉眼辨物時，兩種線索的用途不同。
「冷清的走廊」的冷清多指氣氛，不能直接證明低溫。要有冰涼、刺手等身體感覺，才適合當作觸覺證據。
盲盒紀錄寫：「蓋子一掀，一陣橘皮香先鑽出來；指腹劃過外皮，摸到細小凹點。」燈直到紀錄寫完才打開。
作者先後用了哪兩種感官？|嗅覺、觸覺|味覺、視覺|聽覺、味覺|先聞橘皮香，後以指腹感到凹點。
哪句新紀錄必須開燈才容易完成？|皮上有一塊青綠色的斑|剝開後香氣更濃|表面有一道凸起的稜|顏色和斑紋屬視覺，另外兩句可靠嗅覺或觸覺。

唐代詩風
讀詩風可先圈意象、動詞和觀察焦點，再用自己的話說出氣氛。分辨作者則要另找字號、篇名或可靠題署。李白、杜甫、王維等人的常見風格是理解線索，不能替每篇詩代簽名。
山水詩可用一聲鳥啼襯出寂靜，抒懷詩可用飛馳或高舉的意象寫豪情。先具體說明哪個字讓讀者感到靜或動，才有理由談風格。
同一位詩人可以寫不同風格，不同詩人也都會寫月亮、山川。匿名殘詩只有一個意象時，不宜直接判定作者。
